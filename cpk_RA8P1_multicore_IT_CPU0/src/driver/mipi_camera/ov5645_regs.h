/**
 ******************************************************************************
 * @file    ov5645_regs.h
 * @brief   OV5645 500万像素 MIPI CSI 摄像头寄存器配置
 *
 * OV5645 传感器特性:
 *   - 内置 24MHz 振荡器 (无需外部 XVCLK)
 *   - 2-lane MIPI CSI-2 输出
 *   - I2C 从机地址: 0x3C (7-bit)
 *   - 芯片 ID: 0x300A=0x56, 0x300B=0x45
 *   - 最大分辨率: 2592×1944 @ 15fps
 *   - 输出格式: RGB565 / YUV422 / RAW10
 *
 * 本配置目标:
 *   - 640×480 RGB565 输出
 *   - 2-lane MIPI CSI-2
 *   - 内部 24MHz PLL → VCO ~1GHz → PCLK ~84MHz → MIPI ~500MHz
 ******************************************************************************
 */

